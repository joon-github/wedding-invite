import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import * as fontkit from "fontkit";

const PROJECT_ROOT = process.cwd();
const CANVAS = {
  width: 320,
  height: 108,
  horizontalPadding: 12,
};
const LINE_PRESETS = [
  {
    key: "eyebrow",
    fontSize: 10,
    baseline: 18,
    tracking: 1.3,
    revealWidthEm: 0.44,
  },
  {
    key: "title",
    fontSize: 37,
    baseline: 67,
    tracking: 0.4,
    revealWidthEm: 0.32,
  },
  {
    key: "date",
    fontSize: 11,
    baseline: 96,
    tracking: 0.9,
    revealWidthEm: 0.44,
  },
];
const DEFAULT_TEXT = {
  eyebrow: "THE WEDDING OF",
  title: "범준 그리고 정아",
  date: "2026. 10. 04",
};

function printHelp() {
  process.stdout.write(`
Generate SVG outline and reveal-mask data for HandwritingText.

Usage:
  npm run handwriting:generate -- [options]

Options:
  --eyebrow <text>    Top line (default: "${DEFAULT_TEXT.eyebrow}")
  --title <text>      Main handwritten line (default: "${DEFAULT_TEXT.title}")
  --date <text>       Bottom line (default: "${DEFAULT_TEXT.date}")
  --aria-label <text> Accessible label. Defaults to the lines joined by ", ".
  --out-dir <path>    Output directory (default: src/components)
  --font-css <path>   next/font generated CSS. Usually detected automatically.
  --help              Show this help.

The script uses Nanum Pen Script files generated by next/font in .next.
Run the development server or npm run build once before generating.
`);
}

function readArguments(argv) {
  const options = {
    ...DEFAULT_TEXT,
    ariaLabel: "",
    outDir: path.join(PROJECT_ROOT, "src/components"),
    fontCss: "",
  };
  const optionNames = new Map([
    ["--eyebrow", "eyebrow"],
    ["--title", "title"],
    ["--date", "date"],
    ["--aria-label", "ariaLabel"],
    ["--out-dir", "outDir"],
    ["--font-css", "fontCss"],
  ]);

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];

    if (argument === "--help") {
      printHelp();
      process.exit(0);
    }

    const optionName = optionNames.get(argument);
    if (!optionName) {
      throw new Error(`Unknown option: ${argument}. Use --help for usage.`);
    }

    const value = argv[index + 1];
    if (!value || value.startsWith("--")) {
      throw new Error(`Missing value for ${argument}.`);
    }

    options[optionName] = value;
    index += 1;
  }

  options.outDir = path.resolve(PROJECT_ROOT, options.outDir);
  if (options.fontCss) {
    options.fontCss = path.resolve(PROJECT_ROOT, options.fontCss);
  }
  if (!options.ariaLabel) {
    options.ariaLabel = [
      options.eyebrow,
      options.title,
      options.date,
    ].join(", ");
  }

  return options;
}

function findFiles(directory, predicate) {
  if (!fs.existsSync(directory)) {
    return [];
  }

  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const entryPath = path.join(directory, entry.name);

    if (entry.isDirectory()) {
      return findFiles(entryPath, predicate);
    }

    return predicate(entryPath) ? [entryPath] : [];
  });
}

function parseUnicodeRange(value) {
  return value
    .split(",")
    .map((range) => range.trim())
    .filter(Boolean);
}

function includesCodePoint(range, codePoint) {
  const value = range.replace(/^U\+/i, "");

  if (value.includes("?")) {
    const minimum = Number.parseInt(value.replaceAll("?", "0"), 16);
    const maximum = Number.parseInt(value.replaceAll("?", "F"), 16);
    return codePoint >= minimum && codePoint <= maximum;
  }

  const [start, end = start] = value.split("-");
  return (
    codePoint >= Number.parseInt(start, 16) &&
    codePoint <= Number.parseInt(end, 16)
  );
}

function parseFontFaces(cssPath) {
  const css = fs.readFileSync(cssPath, "utf8");

  return [...css.matchAll(/@font-face\s*\{([^}]+)\}/g)]
    .map((match) => match[1])
    .filter((body) => /font-family:\s*["']?Nanum Pen Script/.test(body))
    .map((body) => {
      const source = body.match(/url\(["']?([^"')]+\.woff2)/)?.[1];
      const ranges = parseUnicodeRange(
        body.match(/unicode-range:\s*([^;]+)/)?.[1] ?? "",
      );

      if (!source) {
        return null;
      }

      return {
        fontPath: path.resolve(path.dirname(cssPath), source),
        ranges,
      };
    })
    .filter(
      (face) =>
        face &&
        face.ranges.length > 0 &&
        fs.existsSync(face.fontPath),
    );
}

function findFontCss(explicitPath, requiredCharacters) {
  const candidates = explicitPath
    ? [explicitPath]
    : findFiles(
        path.join(PROJECT_ROOT, ".next"),
        (filePath) => filePath.endsWith(".css"),
      );

  const usableCandidates = candidates
    .map((cssPath) => ({
      cssPath,
      faces: parseFontFaces(cssPath),
      modifiedAt: fs.statSync(cssPath).mtimeMs,
    }))
    .filter(({ faces }) => faces.length > 0)
    .filter(({ faces }) =>
      requiredCharacters.every((character) => {
        if (character.trim() === "") {
          return true;
        }

        const codePoint = character.codePointAt(0);
        return faces.some((face) =>
          face.ranges.some((range) => includesCodePoint(range, codePoint)),
        );
      }),
    )
    .sort((left, right) => right.modifiedAt - left.modifiedAt);

  if (usableCandidates.length === 0) {
    throw new Error(
      "Could not find generated Nanum Pen Script font subsets in .next. " +
        "Run npm run dev or npm run build once, then retry.",
    );
  }

  return usableCandidates[0];
}

function createFontResolver(faces) {
  const fontCache = new Map();

  return (character) => {
    const codePoint = character.codePointAt(0);
    const face = faces.find((candidate) =>
      candidate.ranges.some((range) => includesCodePoint(range, codePoint)),
    );

    if (!face) {
      throw new Error(
        `Nanum Pen Script has no subset for "${character}" ` +
          `(U+${codePoint.toString(16).toUpperCase()}).`,
      );
    }

    if (!fontCache.has(face.fontPath)) {
      fontCache.set(face.fontPath, fontkit.openSync(face.fontPath));
    }

    return fontCache.get(face.fontPath);
  };
}

function buildLine({ text, preset, resolveFont }) {
  const entries = [];
  let cursor = 0;

  for (const character of text) {
    if (character === " ") {
      cursor += preset.fontSize * 0.34 + preset.tracking;
      continue;
    }

    const font = resolveFont(character);
    const glyph = font.glyphForCodePoint(character.codePointAt(0));
    const scale = preset.fontSize / font.unitsPerEm;
    const advance = glyph.advanceWidth * scale;

    entries.push({
      d: glyph.path.toSVG(),
      cursor,
      scale,
      baseline: preset.baseline,
      bbox: glyph.bbox,
      revealWidth: Number(
        (font.unitsPerEm * preset.revealWidthEm).toFixed(2),
      ),
      line: preset.key,
    });
    cursor += advance + preset.tracking;
  }

  const lineOffset = (CANVAS.width - cursor + preset.tracking) / 2;

  return entries.map((entry) => {
    const transform =
      `translate(${lineOffset.toFixed(3)} 0) ` +
      `translate(${entry.cursor.toFixed(3)} ${entry.baseline}) ` +
      `scale(${entry.scale.toFixed(6)} ${(-entry.scale).toFixed(6)})`;

    return {
      ...entry,
      transform,
      minimumX: lineOffset + entry.cursor + entry.bbox.minX * entry.scale,
      maximumX: lineOffset + entry.cursor + entry.bbox.maxX * entry.scale,
    };
  });
}

function serialize(value) {
  return JSON.stringify(value, null, 2);
}

function createOutlineSource(entries, ariaLabel, viewBox) {
  const paths = entries.map(({ d, transform }) => ({ d, transform }));

  return `export type HandwritingOutline = {
  d: string;
  transform: string;
};

export const HERO_HANDWRITING_OUTLINES = {
  ariaLabel: ${JSON.stringify(ariaLabel)},
  viewBox: ${JSON.stringify(viewBox)},
  paths: ${serialize(paths)} satisfies HandwritingOutline[],
} as const;
`;
}

function createMaskSource(entries, ariaLabel, viewBox) {
  const groups = entries.map((entry, outlineIndex) => ({
    outlineIndex,
    line: entry.line,
    strokes: [
      {
        d: entry.d,
        transform: entry.transform,
        revealWidth: entry.revealWidth,
      },
    ],
  }));

  return `export type HandwritingStroke = {
  d: string;
  revealWidth: number;
  transform?: string;
};

export type HandwritingMaskGroup = {
  outlineIndex: number;
  line: "eyebrow" | "title" | "date";
  strokes: readonly HandwritingStroke[];
};

// Generated masks are a baseline. Replace one group's strokes with
// hand-tuned centerline paths when exact pen order matters.
export const HERO_HANDWRITING_ARTWORK = {
  ariaLabel: ${JSON.stringify(ariaLabel)},
  viewBox: ${JSON.stringify(viewBox)},
  groups: ${serialize(groups)} satisfies HandwritingMaskGroup[],
} as const;
`;
}

function writeAtomically(filePath, contents) {
  const temporaryPath = `${filePath}.tmp`;
  fs.writeFileSync(temporaryPath, contents);
  fs.renameSync(temporaryPath, filePath);
}

function main() {
  const options = readArguments(process.argv.slice(2));
  const requiredCharacters = [
    ...new Set(
      [options.eyebrow, options.title, options.date]
        .join("")
        .split(""),
    ),
  ];
  const { cssPath, faces } = findFontCss(
    options.fontCss,
    requiredCharacters,
  );
  const resolveFont = createFontResolver(faces);
  const textByLine = {
    eyebrow: options.eyebrow,
    title: options.title,
    date: options.date,
  };
  const entries = LINE_PRESETS.flatMap((preset) =>
    buildLine({
      text: textByLine[preset.key],
      preset,
      resolveFont,
    }),
  );

  if (entries.length === 0) {
    throw new Error("At least one line must contain a visible character.");
  }

  const minimumX = Math.max(
    0,
    Math.floor(
      Math.min(...entries.map((entry) => entry.minimumX)) -
        CANVAS.horizontalPadding,
    ),
  );
  const maximumX = Math.min(
    CANVAS.width,
    Math.ceil(
      Math.max(...entries.map((entry) => entry.maximumX)) +
        CANVAS.horizontalPadding,
    ),
  );
  const viewBox = `${minimumX} 0 ${maximumX - minimumX} ${CANVAS.height}`;

  fs.mkdirSync(options.outDir, { recursive: true });
  const outlinePath = path.join(
    options.outDir,
    "handwriting-text.outlines.ts",
  );
  const maskPath = path.join(options.outDir, "handwriting-text.paths.ts");

  writeAtomically(
    outlinePath,
    createOutlineSource(entries, options.ariaLabel, viewBox),
  );
  writeAtomically(
    maskPath,
    createMaskSource(entries, options.ariaLabel, viewBox),
  );

  process.stdout.write(
    [
      `Generated ${entries.length} glyphs.`,
      `Font CSS: ${path.relative(PROJECT_ROOT, cssPath)}`,
      `Outlines: ${path.relative(PROJECT_ROOT, outlinePath)}`,
      `Masks: ${path.relative(PROJECT_ROOT, maskPath)}`,
      `ViewBox: ${viewBox}`,
    ].join("\n") + "\n",
  );
}

try {
  main();
} catch (error) {
  process.stderr.write(
    `${error instanceof Error ? error.message : String(error)}\n`,
  );
  process.exitCode = 1;
}
